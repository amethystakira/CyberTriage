-- PostgreSQL schema for CyberTriage.
-- The live SQLite schema is created from SQLAlchemy metadata in backend/app/database.py.

CREATE TABLE IF NOT EXISTS investigations (
    row_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    investigator TEXT NOT NULL,
    date TEXT NOT NULL,
    status TEXT NOT NULL
        CHECK (status IN ('Pending', 'Analyzing', 'Completed')),
    severity TEXT NOT NULL
        CHECK (severity IN ('Unassigned', 'Low', 'Medium', 'High', 'Critical'))
);

CREATE TABLE IF NOT EXISTS evidence (
    evidence_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NULL REFERENCES investigations(case_id),
    original_name TEXT NOT NULL,
    stored_name TEXT NOT NULL,
    sha256 TEXT NOT NULL CHECK (length(sha256) = 64),
    size_bytes INTEGER NOT NULL CHECK (size_bytes >= 0),
    uploaded_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_evidence_stored_name
    ON evidence (stored_name);

CREATE TABLE IF NOT EXISTS findings (
    finding_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NULL REFERENCES investigations(case_id),
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    severity TEXT NOT NULL
        CHECK (severity IN ('Low', 'Medium', 'High', 'Critical')),
    status TEXT NOT NULL DEFAULT 'Open'
        CHECK (status IN ('Open', 'Resolved')),
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS analysis_runs (
    run_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id INTEGER NOT NULL REFERENCES evidence(evidence_id),
    summary TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS analysis_indicators (
    indicator_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analysis_runs(run_id),
    ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
    indicator_type TEXT NOT NULL,
    value TEXT NOT NULL,
    reason TEXT NOT NULL,
    CONSTRAINT uq_analysis_indicator_order UNIQUE (run_id, ordinal)
);

CREATE TABLE IF NOT EXISTS timeline_events (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NULL REFERENCES investigations(case_id),
    event_type TEXT NOT NULL,
    description TEXT NOT NULL,
    occurred_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_evidence_case_id ON evidence (case_id);
CREATE INDEX IF NOT EXISTS ix_findings_case_id ON findings (case_id);
CREATE INDEX IF NOT EXISTS ix_analysis_runs_evidence_id ON analysis_runs (evidence_id);
CREATE INDEX IF NOT EXISTS ix_analysis_indicators_run_id ON analysis_indicators (run_id);
CREATE INDEX IF NOT EXISTS ix_timeline_events_case_id ON timeline_events (case_id);
CREATE INDEX IF NOT EXISTS ix_timeline_events_occurred_at ON timeline_events (occurred_at);
